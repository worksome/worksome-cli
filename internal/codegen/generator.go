func buildQueryArgs(args []Argument) string {
	if len(args) == 0 {
		return ""
	}
	var parts []string
	for _, a := range args {
		gqlType := a.Type.Name
		if a.Type.IsList {
			gqlType = "[" + a.Type.ListItem.Name + "]"
			if a.Type.ListItem.IsRequired {
				gqlType = "[" + a.Type.ListItem.Name + "!]"
			}
		}
		if a.Type.IsRequired {
			gqlType += "!"
		}
		def := ""
		if a.DefaultValue != "" {
			def = " = " + a.DefaultValue
		}
		parts = append(parts, fmt.Sprintf("$%s: %s%s", a.Name, gqlType, def))
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

func buildQueryCallArgs(args []Argument) string {
	if len(args) == 0 {
		return ""
	}
	var parts []string
	for _, a := range args {
		parts = append(parts, fmt.Sprintf("%s: $%s", a.Name, a.Name))
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

func buildMutationArgs(args []Argument) string {
	if len(args) == 0 {
		return ""
	}
	var parts []string
	for _, a := range args {
		gqlType := a.Type.Name
		if a.Type.IsList {
			inner := a.Type.ListItem.Name
			if a.Type.ListItem.IsRequired {
				inner += "!"
			}
			gqlType = "[" + inner + "]"
		}
		if a.Type.IsRequired {
			gqlType += "!"
		}
		parts = append(parts, fmt.Sprintf("$%s: %s", a.Name, gqlType))
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

func buildMutationCallArgs(args []Argument) string {
	if len(args) == 0 {
		return ""
	}
	var parts []string
	for _, a := range args {
		parts = append(parts, fmt.Sprintf("%s: $%s", a.Name, a.Name))
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

func buildSelectionHint(t TypeRef) string {
	if t.IsPaginator {
		return "{ id }"
	}
	if t.IsList {
		return "{ id }"
	}
	if t.IsScalar || t.IsEnum {
		return ""
	}
	return "{ id }"
}

func hasIDArg(args []Argument) bool {
	for _, a := range args {
		if a.Name == "id" {
			return true
		}
	}
	return false
}
