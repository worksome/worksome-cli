// Generator produces Go source files from a parsed Schema IR.
type Generator struct {
	schema     *Schema
	outputDir  string
	modulePath string
}

// NewGenerator creates a new code generator.
func NewGenerator(schema *Schema, outputDir, modulePath string) *Generator {
	return &Generator{
		schema:     schema,
		outputDir:  outputDir,
		modulePath: modulePath,
	}
}

// Generate produces all Go source files.
func (g *Generator) Generate() error {
	if err := os.MkdirAll(filepath.Join(g.outputDir, "types"), 0o755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(g.outputDir, "queries"), 0o755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(g.outputDir, "commands"), 0o755); err != nil {
		return err
	}

	generators := []struct {
		name string
		fn   func() error
	}{
		{"enums", g.generateEnums},
		{"types", g.generateTypes},
		{"inputs", g.generateInputs},
		{"queries", g.generateQueries},
		{"commands", g.generateCommands},
		{"root", g.generateRoot},
	}

	for _, gen := range generators {
		fmt.Fprintf(os.Stderr, "  generating %s...\n", gen.name)
		if err := gen.fn(); err != nil {
			return fmt.Errorf("generating %s: %w", gen.name, err)
		}
	}

	return nil
}

func (g *Generator) generateEnums() error {
	tmpl := template.Must(template.New("enums").Parse(enumsTemplate))
	return g.writeTemplate(tmpl, filepath.Join(g.outputDir, "types", "enums.go"), map[string]any{
		"Enums": g.schema.Enums,
	})
}

func (g *Generator) generateTypes() error {
	tmpl := template.Must(template.New("types").Funcs(templateFuncs).Parse(typesTemplate))
	return g.writeTemplate(tmpl, filepath.Join(g.outputDir, "types", "types.go"), map[string]any{
		"Objects":    g.schema.Objects,
		"Interfaces": g.schema.Interfaces,
		"Unions":     g.schema.Unions,
	})
}

func (g *Generator) generateInputs() error {
	tmpl := template.Must(template.New("inputs").Funcs(templateFuncs).Parse(inputsTemplate))
	return g.writeTemplate(tmpl, filepath.Join(g.outputDir, "types", "inputs.go"), map[string]any{
		"Inputs": g.schema.Inputs,
	})
}

func (g *Generator) generateQueries() error {
	tmpl := template.Must(template.New("queries").Funcs(templateFuncs).Parse(queriesTemplate))
	return g.writeTemplate(tmpl, filepath.Join(g.outputDir, "queries", "queries.go"), map[string]any{
		"Resources":  g.schema.Resources,
		"ModulePath": g.modulePath,
	})
}

func (g *Generator) generateCommands() error {
	tmpl := template.Must(template.New("commands").Funcs(templateFuncs).Parse(commandsTemplate))
	return g.writeTemplate(tmpl, filepath.Join(g.outputDir, "commands", "commands.go"), map[string]any{
		"Resources":  g.schema.Resources,
		"ModulePath": g.modulePath,
	})
}

func (g *Generator) generateRoot() error {
	tmpl := template.Must(template.New("root").Funcs(templateFuncs).Parse(rootTemplate))
	return g.writeTemplate(tmpl, filepath.Join(g.outputDir, "commands", "root.go"), map[string]any{
		"Resources":  g.schema.Resources,
		"ModulePath": g.modulePath,
	})
}

func (g *Generator) writeTemplate(tmpl *template.Template, path string, data any) error {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("executing template for %s: %w", path, err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		// Write unformatted for debugging
		os.WriteFile(path+".unformatted", buf.Bytes(), 0o644)
		return fmt.Errorf("formatting %s: %w (unformatted written to %s.unformatted)", path, err, path)
	}

	return os.WriteFile(path, formatted, 0o644)
}

var templateFuncs = template.FuncMap{
	"lower":     strings.ToLower,
	"kebab":     toKebabCase,
	"pascal":    toPascalCase,
	"hasPrefix": strings.HasPrefix,
	"hasSuffix": strings.HasSuffix,
	"trimPrefix": strings.TrimPrefix,
	"join":      strings.Join,
	"jsonTag": func(name string, omitempty bool) string {
		if omitempty {
			return fmt.Sprintf("`json:\"%s,omitempty\"`", name)
		}
		return fmt.Sprintf("`json:\"%s\"`", name)
	},
	"isPtr": func(goType string) bool {
		return strings.HasPrefix(goType, "*")
	},
	"deref": func(goType string) string {
		return strings.TrimPrefix(goType, "*")
	},
	"quote": func(s string) string {
		return fmt.Sprintf("%q", s)
	},
	"commentBlock": func(s string) string {
		if s == "" {
			return ""
		}
		lines := strings.Split(s, "\n")
		var result []string
		for _, line := range lines {
			result = append(result, "// "+line)
		}
		return strings.Join(result, "\n")
	},
}

