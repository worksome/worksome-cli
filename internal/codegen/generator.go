	// Register additional template functions for query building
	templateFuncs["buildQueryArgs"] = buildQueryArgs
	templateFuncs["buildQueryCallArgs"] = buildQueryCallArgs
	templateFuncs["buildMutationArgs"] = buildMutationArgs
	templateFuncs["buildMutationCallArgs"] = buildMutationCallArgs
	templateFuncs["buildSelectionHint"] = buildSelectionHint
	templateFuncs["hasIDArg"] = hasIDArg
